  messages.push({who:'给网站管理员或办公室',text:`你好，我们准备${team?'搭一个多人测试环境':'先在本地试用，顺便了解后续条件'}。${hostText}\n${accessText}\n方便时请回复：负责部门、测试空间、存放地区、访问方式、是否需要预算审批。请只发这些说明。`});

